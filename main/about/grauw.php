<p><em>History:</em><br />
I started MSX Assembly programming when I was about 12, 13 years old. Before that, I programmed a little in Basic, and I also know a little Logo ;). Currently I am still keeping my MSX spirit alive with amongst others programming, writing an article once in a while, chatting on the #msxdev@rizon IRC channel, and a little web design.</p>

<p>As far as programming is concerned, I have started quite some projects which I never finished (yet! ^_^), so there aren't too many programs of which you can say, ah, that's something Grauw created. However, you might remember the diskmagazine Track and a couple of music disks from the Dutch group Datax, and I also coded a part of one of Kenda's music disks (they were from Belgium). After that, I created a couple of small programs, for example a tool with which you can send and receive files to and from a TI-83 calculator, and I also made a dev kit for it (since the TI-83 is Z80 based, you can just use your favorite MSX Assembler). Another thing I made is a fast ANSI RS232 terminal, however it is still very very alpha, and also a standalone YMODEM-G download tool, but I haven't published that one yet. It reaches a speed of 7kb/s, and I'm quite proud of that ^_^ (about twice as fast as Erix).</p>

<p>Nowadays I am a member of TNI, and I also organize the MSX fair in Bussum. Projects I am currently working on are some experiments with the Gfx9000, DOS 3, which if it is ever finished should become pretty awesome, and occasionally a couple of datacommunications related projects. I am also working on a few game-engines (RPG, RTS), with the help of my brand new v9958. What exactly I work on depends on my mood, and hence they're not progressing really fast as I want to do them all at the same time :).</p>


