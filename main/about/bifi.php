<p><em>History:</em><br />
My MSX Experience started (just like many others) in 1984 with MSX&#160;1. I started to program Basic few months later and from 1986 I set my first steps in Assembly programming. I learned it quite well by recreating graphical effects I've seen in games and writing my own tape access routines. I kinda joined the real MSX scene from 1992 by going to the regular MSX fairs in Tilburg and Bussum (which used to be in Zandvoort in the early days) and MSX meetings. I also wrote articles about MSX for several computer clubs. Nowadays my MSX days are (apart from starting up my MSX and actually doing stuff with it) being a regular stick-in-the-mud ;) in #msxdev@Rizon channels and doing some HTML &amp; JavaScript stuff.</p>

<p>Currently, my programming experience reaches not only my own projects, supporting other programmers and bugfixing, but also to active MSX groups like Delta Soft, by helping them with things they just can't figure out, giving input and having fun. If you want to know what I have written in the past and recently, you should take a look at my <A HREF="http://www.bifi.msxnet.org/" TARGET="_blank">Home Page</A>. I've written many articles about how devices are used, extra memory can be accessed and additional features can be used in assembly. I also made small tools for Gfx9000 / Video9000 and MoonSound.</p>


<h2>BiFi @ MAP</h2>

<p>I was member of the team that first launched the idea of the MSX Assembly Page (MAP for short) since we (Chaos, d-fader and myself) noticed many programmers who want to start with assembly on MSX started to ask the same questions all over again. Since then we felt the need to set up an online library with resources, articles, source examples, downloads, etc. regarding MSX Assembly. We started a preliminary site somewhere on Geocities until Grauw joined the team.</p>

